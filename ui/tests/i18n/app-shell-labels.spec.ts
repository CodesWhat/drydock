it.each(Object.entries(expected))(
  'provides translated search and theme controls in %s',
  (locale, labels) => {
    const [light, system, dark, all, pages, containers, runtime, config, navigation, connector] =
      labels;
    const messages = i18n.global.getLocaleMessage(locale as SupportedLocale) as any;
    expect(messages.appShell.themeToggle.variant).toEqual({ light, system, dark });
    expect(messages.appShell.layout.search.scope).toEqual({
      all,
      pages,
      containers,
      runtime,
      config,
    });
    expect(messages.appShell.layout.search.group).toEqual({
      navigation,
      containers,
      runtime,
      configuration: config,
    });
    expect(messages.appShell.layout.search.atOrConnector).toBe(connector);
  },
);
